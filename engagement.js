/*
 * Anonymous usage signals for ArcadeRTFM.
 *
 * Only records actions, never search text, URLs, machine IDs, visitor IDs,
 * cookies, IP addresses, or device fingerprints in the payload.
 * Cloudflare already sees normal HTTP request metadata at the edge.
 * The signal endpoints are static files: no database, third-party collector,
 * or persistent browser state is involved.
 */
(() => {
  'use strict';

  // Respect explicit browser privacy preferences.
  if (navigator.globalPrivacyControl === true ||
      navigator.doNotTrack === '1' ||
      navigator.msDoNotTrack === '1') return;

  const validSignals = new Set([
    'search-results', 'search-empty', 'machine-open', 'manual-open'
  ]);

  function recordSignal(signal) {
    if (!validSignals.has(signal)) return;

    // No query parameters, page URL, referrer, cookie or identity is sent.
    // Each GET can be counted by path using existing Cloudflare HTTP analytics.
    fetch('/signals/' + signal + '.txt', {
      method: 'GET',
      mode: 'same-origin',
      credentials: 'omit',
      cache: 'no-store',
      referrerPolicy: 'no-referrer',
      keepalive: true
    }).catch(() => {
      // Analytics is never allowed to interrupt using the archive.
    });
  }

  // Count actual manual-link clicks and opening machine details. These are
  // user actions, not page requests generated by search-engine crawlers.
  document.addEventListener('click', event => {
    if (!event.isTrusted || !event.target?.closest) return;

    if (event.target.closest('a.manual-link')) {
      recordSignal('manual-open');
      return;
    }

    const trigger = event.target.closest('.machine-head, .badge-manual');
    const machine = trigger?.closest('.machine');
    if (machine && !machine.classList.contains('open')) {
      recordSignal('machine-open');
    }
  }, true);

  // A search counts only after typing has settled. Search terms stay in the
  // browser; even the submitted signal does not contain the query or result
  // count. We only distinguish searches returning results from empty ones.
  const searchInput = document.getElementById('search');
  if (searchInput) {
    let debounce;
    let lastReported = '';

    searchInput.addEventListener('input', event => {
      if (!event.isTrusted) return;
      clearTimeout(debounce);

      const term = searchInput.value.trim().toLowerCase().replace(/\s+/g, ' ');
      if (term.length < 2) return;

      debounce = setTimeout(() => {
        const current = searchInput.value.trim().toLowerCase().replace(/\s+/g, ' ');
        if (current !== term || current === lastReported) return;
        lastReported = current;

        const empty = document.querySelector('#results-container .no-results');
        recordSignal(empty ? 'search-empty' : 'search-results');
      }, 900);
    });
  }
})();
